"""
Context-Aware Security Remediation Engine for IPsec VPNs.
Dynamically generates hardened configuration templates and CLI snippets
tailored to extracted peer IPs, modes, and specific compliance failures
for StrongSwan, Cisco IOS-XE, and VyOS.
"""

from typing import List
from backend.app.schemas.models import (
    SecurityAssociation, ComplianceFinding, ComplianceStatus, RemediationConfig
)


class RemediationGenerator:
    """Generates platform-specific, context-aware configurations to patch detected flaws."""

    def generate_remediation_configs(
        self,
        sa: SecurityAssociation,
        findings: List[ComplianceFinding]
    ) -> List[RemediationConfig]:
        configs: List[RemediationConfig] = []

        local_ip = sa.peer_ips[0] if len(sa.peer_ips) >= 1 else "<LOCAL_GATEWAY_IP>"
        remote_ip = sa.peer_ips[1] if len(sa.peer_ips) >= 2 else "<REMOTE_GATEWAY_IP>"
        target_mode = "tunnel"  # Always recommend tunnel mode for gateway security

        issues = [
            f"{f.rule_id}: {f.title} ({f.current_value} -> {f.recommended_value})"
            for f in findings
            if f.status in (ComplianceStatus.FAIL, ComplianceStatus.WARNING) and "PQC-RADAR" not in f.rule_id
        ]
        if not issues:
            issues = ["Baseline hardened posture verified; minor PQC roadmap preparation recommended."]

        issues_header = "\n".join(f"#   - [FIX] {item}" for item in issues)
        cisco_header = "\n".join(f"!   - [FIX] {item}" for item in issues)

        # 1. StrongSwan (swanctl.conf)
        strongswan_conf = f"""# Context-Aware Remediation Generated by IPsec Sentinel AI
# Detected Peer Endpoints: {local_ip} <--> {remote_ip}
# Current Profile: {sa.ike_version.value} | {sa.encryption_algorithm} | {sa.dh_group or 'Unknown DH'} | Mode: {sa.mode.value}
#
# Addressed Compliance Findings:
{issues_header}

connections {{
    hardened-vpn {{
        version = 2
        local_addrs = {local_ip}
        remote_addrs = {remote_ip}

        # Enforce AEAD (AES-256-GCM) with PRF-SHA384 and ECC Group 19/20 (Removes legacy fallbacks)
        proposals = aes256gcm16-prfsha384-ecp256, aes256gcm16-prfsha512-ecp384
        rekey_time = 28800s

        local {{
            auth = psk
            id = {local_ip}
        }}
        remote {{
            auth = psk
            id = {remote_ip}
        }}

        children {{
            hardened-child {{
                mode = {target_mode}
                # Enforce AEAD + Perfect Forward Secrecy (ECP-256) + ESN
                esp_proposals = aes256gcm16-ecp256-esn, aes256gcm16-ecp384-esn
                rekey_time = 3600s
                rekey_bytes = 1073741824
                replay_window = 128
                dpd_action = restart
            }}
        }}
    }}
}}

secrets {{
    ike-hardened {{
        id-local = {local_ip}
        id-remote = {remote_ip}
        secret = "<REPLACE_WITH_256BIT_RANDOM_PSK>"
    }}
}}
"""
        configs.append(RemediationConfig(
            platform="StrongSwan (swanctl.conf)",
            config_snippet=strongswan_conf,
            description=f"Tailored StrongSwan configuration for peers {local_ip} <-> {remote_ip}, migrating from {sa.ike_version.value}/{sa.encryption_algorithm} to hardened IKEv2 AEAD + PFS + ESN.",
            addressed_issues=issues,
        ))

        # 2. Cisco IOS-XE CLI
        cisco_cli = f"""! Context-Aware Cisco IOS-XE Remediation Commands
! Target Peers: {local_ip} <--> {remote_ip}
! Replaces: {sa.ike_version.value} / {sa.encryption_algorithm} / {sa.dh_group or 'Unknown DH'}
!
{cisco_header}

configure terminal

! 1. Hardened IKEv2 Proposal & Policy (No weak fallbacks)
crypto ikev2 proposal IKEV2-HARDENED-PROPOSAL
 encryption aes-gcm-256
 prf sha384
 group 19
 exit

crypto ikev2 policy IKEV2-HARDENED-POLICY
 proposal IKEV2-HARDENED-PROPOSAL
 exit

! 2. IKEv2 Keyring & Profile
crypto ikev2 keyring IKEV2-KEYRING
 peer PEER-{remote_ip}
  address {remote_ip}
  pre-shared-key <STRONG_RANDOM_PSK_MIN_32_CHARS>
  exit
 exit

crypto ikev2 profile IKEV2-HARDENED-PROFILE
 match identity remote address {remote_ip}
 identity local address {local_ip}
 authentication remote pre-share
 authentication local pre-share
 keyring local IKEV2-KEYRING
 lifetime 28800
 dpd 10 2 on-demand
 exit

! 3. Hardened IPsec Transform Set (AES-GCM-256 AEAD, Tunnel Mode)
crypto ipsec transform-set TS-AES-GCM esp-gcm 256
 mode {target_mode}
 exit

! 4. IPsec Profile with PFS Group 19 & Replay Window
crypto ipsec security-association replay window-size 128
crypto ipsec profile IPSEC-HARDENED-PROFILE
 set transform-set TS-AES-GCM
 set pfs group19
 set ikev2-profile IKEV2-HARDENED-PROFILE
 set security-association lifetime seconds 3600
 exit

end
write memory
"""
        configs.append(RemediationConfig(
            platform="Cisco IOS-XE (CLI)",
            config_snippet=cisco_cli,
            description=f"Cisco IOS-XE CLI patch tailored to {local_ip} <-> {remote_ip} enforcing AES-GCM-256, PFS Group 19, and 128-packet anti-replay protection.",
            addressed_issues=issues,
        ))

        # 3. VyOS CLI
        vyos_cli = f"""# Context-Aware VyOS 1.4+ Remediation Script
# Target Peers: {local_ip} <--> {remote_ip}
#
{issues_header}

set vpn ipsec ike-group HARDENED-IKE key-exchange 'ikev2'
set vpn ipsec ike-group HARDENED-IKE proposal 10 dh-group '19'
set vpn ipsec ike-group HARDENED-IKE proposal 10 encryption 'aes256gcm'
set vpn ipsec ike-group HARDENED-IKE proposal 10 prf 'sha384'
set vpn ipsec ike-group HARDENED-IKE lifetime '28800'

set vpn ipsec esp-group HARDENED-ESP mode '{target_mode}'
set vpn ipsec esp-group HARDENED-ESP pfs 'dh-group19'
set vpn ipsec esp-group HARDENED-ESP proposal 10 encryption 'aes256gcm'
set vpn ipsec esp-group HARDENED-ESP lifetime '3600'

set vpn ipsec site-to-site peer {remote_ip} local-address '{local_ip}'
set vpn ipsec site-to-site peer {remote_ip} authentication mode 'pre-shared-secret'
set vpn ipsec site-to-site peer {remote_ip} authentication pre-shared-secret '<SECRET_KEY>'
set vpn ipsec site-to-site peer {remote_ip} default-esp-group 'HARDENED-ESP'
set vpn ipsec site-to-site peer {remote_ip} ike-group 'HARDENED-IKE'
commit
save
"""
        configs.append(RemediationConfig(
            platform="VyOS / Linux Router",
            config_snippet=vyos_cli,
            description=f"VyOS declarative configuration binding {local_ip} <-> {remote_ip} to IKEv2 AEAD and strict PFS Group 19.",
            addressed_issues=issues,
        ))

        return configs
